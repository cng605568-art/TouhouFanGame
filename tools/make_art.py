def rough_rect(x, y, w, h, jitter, rnd, step=14):
    p = []
    for i in range(int(w // step) + 1):
        p.append((x + min(w, i * step), y + rnd.uniform(-jitter, jitter)))
    for i in range(1, int(h // step) + 1):
        p.append((x + w + rnd.uniform(-jitter, jitter), y + min(h, i * step)))
    for i in range(int(w // step), -1, -1):
        p.append((x + min(w, i * step), y + h + rnd.uniform(-jitter, jitter)))
    for i in range(int(h // step), 0, -1):
        p.append((x + rnd.uniform(-jitter, jitter), y + min(h, i * step)))
    return "M" + " L".join(pts(q) for q in p) + " Z"


