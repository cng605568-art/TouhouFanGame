def wood_grain(x0, x1, y0, y1, color, opacity, seed, n=9):
    rnd = random.Random(seed)
    lines = []
    for i in range(n):
        y = y0 + (y1 - y0) * (i + 0.5) / n + rnd.uniform(-3, 3)
        segs = ["M%s" % pts((x0, y))]
        x = x0
        while x < x1:
            step = rnd.uniform(50, 90)
            nx = min(x1, x + step)
            segs.append("Q%s %s" % (pts(((x + nx) / 2.0, y + rnd.uniform(-5, 5))), pts((nx, y + rnd.uniform(-1.5, 1.5)))))
            x = nx
        lines.append(" ".join(segs))
    # A knot or two.
    knots = []
    for _ in range(2):
        kx = rnd.uniform(x0 + 60, x1 - 60)
        ky = rnd.uniform(y0 + 14, y1 - 14)
        knots.append('<ellipse cx="%s" cy="%s" rx="%s" ry="%s" fill="none" stroke="%s" stroke-width="1.5" stroke-opacity="%s"/>' % (
            f(kx), f(ky), f(rnd.uniform(9, 14)), f(rnd.uniform(3, 5)), color, f(opacity)))
    return '<path d="%s" fill="none" stroke="%s" stroke-width="1.6" stroke-opacity="%s" stroke-linecap="round"/>\n%s' % (
        " ".join(lines), color, f(opacity), "\n".join(knots))


