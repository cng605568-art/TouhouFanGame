def make_stamp():
    W, H = 600, 320
    rnd = random.Random(9)
    # Ink gaps, only on the printed bands so nothing floats over the scene.
    specks = []
    bands = [(14, 30), (40, 47)]
    for _ in range(60):
        a, b = rnd.choice(bands)
        t = rnd.uniform(a + 2, b - 2)
        side = rnd.randrange(4)
        if side == 0:
            x, y = rnd.uniform(a, W - a), t
        elif side == 1:
            x, y = rnd.uniform(a, W - a), H - t
        elif side == 2:
            x, y = t, rnd.uniform(a, H - a)
        else:
            x, y = W - t, rnd.uniform(a, H - a)
        specks.append('<circle cx="%s" cy="%s" r="%s" fill="%s" fill-opacity="%s"/>' % (
            f(x), f(y), f(rnd.uniform(1.2, 3.2)), PARCHMENT, f(rnd.uniform(0.3, 0.6))))
    body = "\n".join([
        '<path d="%s %s" fill="%s" fill-rule="evenodd" fill-opacity="0.92"/>' % (
            rough_rect(14, 14, W - 28, H - 28, 2.6, rnd), rough_rect(30, 30, W - 60, H - 60, 1.8, rnd), VERMILION),
        '<path d="%s %s" fill="%s" fill-rule="evenodd" fill-opacity="0.92"/>' % (
            rough_rect(40, 40, W - 80, H - 80, 1.6, rnd), rough_rect(47, 47, W - 94, H - 94, 1.2, rnd), VERMILION),
        "\n".join(specks),
    ])
    write(os.path.join(GUI, "stamp_frame.svg"), svg(W, H, body, "verdict stamp frame"))


