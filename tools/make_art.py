def make_burst():
    W, H = 1120, 600
    cx, cy = 560, 300
    rnd = random.Random(3)
    n = 26
    outer, inner = [], []
    for i in range(n * 2):
        a = 2 * math.pi * i / (n * 2) + rnd.uniform(-0.04, 0.04)
        big = i % 2 == 0
        kx = rnd.uniform(0.92, 1.06) if big else rnd.uniform(0.74, 0.8)
        rx, ry = 540 * kx, 280 * kx
        outer.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
        inner.append((cx + rx * 0.9 * math.cos(a), cy + ry * 0.86 * math.sin(a)))
    d_out = "M" + " L".join(pts(p) for p in outer) + " Z"
    d_in = "M" + " L".join(pts(p) for p in inner) + " Z"
    body = "\n".join([
        "<defs>", rad("paper", [(0, "#FFFDF6"), (0.7, PARCHMENT), (1, "#E8D9B4")]), "</defs>",
        '<path d="%s" fill="%s" stroke="%s" stroke-width="16" stroke-linejoin="miter"/>' % (d_out, CRIMSON, CRIMSON),
        '<path d="%s" fill="url(#paper)" stroke="%s" stroke-width="5" stroke-linejoin="miter"/>' % (d_in, GOLD),
    ])
    write(os.path.join(GUI, "burst.svg"), svg(W, H, body, "objection burst"))


def make_speedlines():
    W, H = 1920, 1080
    cx, cy = 960, 470
    rnd = random.Random(5)
    wedges = []
    a = 0.0
    while a < 2 * math.pi:
        width = rnd.uniform(0.006, 0.02)
        r0 = rnd.uniform(330, 520)
        r1 = 1500
        p0 = (cx + r0 * math.cos(a), cy + r0 * math.sin(a))
        p1 = (cx + r1 * math.cos(a - width), cy + r1 * math.sin(a - width))
        p2 = (cx + r1 * math.cos(a + width), cy + r1 * math.sin(a + width))
        wedges.append("M%s L%s L%s Z" % (pts(p0), pts(p1), pts(p2)))
        a += rnd.uniform(0.05, 0.11)
    body = '<path d="%s" fill="#FFFFFF" fill-opacity="0.55"/>' % " ".join(wedges)
    write(os.path.join(GUI, "speedlines.svg"), svg(W, H, body, "speed lines"))


def rough_rect(x, y, w, h, jitter, rnd, step=14):
    p = []
    for i in range(int(w // step) + 1):
        p.append((x + min(w, i * step), y + rnd.uniform(-jitter, jitter)))
    for i in range(1, int(h // step) + 1):
        p.append((x + w + rnd.uniform(-jitter, jitter), y + min(h, i * step)))
    for i in range(int(w // step), -1, -1):
        p.append((x + min(w, i * step), y + h + rnd.uniform(-jitter, jitter)))
    for i in range(int(h // step), 0, -1):
        p.append((x + rnd.uniform(-jitter, jitter), y + min(h, i * step)))
    return "M" + " L".join(pts(q) for q in p) + " Z"


