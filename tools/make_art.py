def asanoha_paths(w, h, s, ox=0.0, oy=0.0):
    """
    Hemp-leaf lattice: a triangular grid whose triangles are split into three
    kites by spokes from each centroid. Returns (grid_path, spoke_path).
    """
    th = s * math.sqrt(3) / 2.0
    grid = []
    spokes = []

    rows = int(h / th) + 3
    cols = int(w / s) + 3

    for j in range(-1, rows):
        y0 = oy + j * th
        y1 = y0 + th
        shift = (s / 2.0) if j % 2 else 0.0
        # Horizontal lattice line.
        grid.append("M%s L%s" % (pts((-10, y0)), pts((w + 10, y0))))

        for i in range(-1, cols):
            xa = ox + i * s + shift
            # Up-pointing triangle: (xa, y1) (xa + s, y1) (xa + s/2, y0)
            up = [(xa, y1), (xa + s, y1), (xa + s / 2.0, y0)]
            # Down-pointing triangle: (xa + s/2, y0) (xa + 3s/2, y0) (xa + s, y1)
            dn = [(xa + s / 2.0, y0), (xa + 1.5 * s, y0), (xa + s, y1)]
            for tri in (up, dn):
                cx = sum(p[0] for p in tri) / 3.0
                cy = sum(p[1] for p in tri) / 3.0
                if cx < -s or cx > w + s or cy < -s or cy > h + s:
                    continue
                for p in tri:
                    spokes.append("M%s L%s" % (pts((cx, cy)), pts(p)))
            # One diagonal of each family per up-triangle covers the lattice.
            grid.append("M%s L%s" % (pts(up[0]), pts(up[2])))
            grid.append("M%s L%s" % (pts(up[1]), pts(up[2])))

    return " ".join(grid), " ".join(spokes)


def mirror_halo(cx, cy, r):
    """Concentric rings and rays: the Cleansed Crystal Mirror motif."""
    out = []
    rays = []
    for k in range(48):
        a = 2 * math.pi * k / 48.0
        r0 = r * 0.74
        r1 = r * (0.98 if k % 2 == 0 else 0.88)
        rays.append("M%s L%s" % (
            pts((cx + r0 * math.cos(a), cy + r0 * math.sin(a))),
            pts((cx + r1 * math.cos(a), cy + r1 * math.sin(a)))))
    out.append('<path d="%s" fill="none" stroke="%s" stroke-width="3" stroke-opacity="0.22" stroke-linecap="round"/>' % (" ".join(rays), GOLD))
    for rr, sw, op in ((r, 4, 0.30), (r * 0.72, 2.5, 0.28), (r * 0.66, 1.5, 0.2), (r * 1.06, 1.5, 0.16)):
        out.append('<circle cx="%s" cy="%s" r="%s" fill="none" stroke="%s" stroke-width="%s" stroke-opacity="%s"/>' % (
            f(cx), f(cy), f(rr), GOLD, f(sw), f(op)))
    return "\n".join(out)


