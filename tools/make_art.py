def ellipse_below(cx, cy, rx, ry, cut, fill, extra=""):
    """An ellipse with everything above y=cut removed (no clip paths needed)."""
    if cut <= cy - ry:
        return '<ellipse cx="%s" cy="%s" rx="%s" ry="%s" fill="%s"%s/>' % (f(cx), f(cy), f(rx), f(ry), fill, extra)
    t = (cut - cy) / float(ry)
    dx = rx * math.sqrt(max(0.0, 1.0 - t * t))
    large = 1 if cut < cy else 0
    return '<path d="M%s A%s %s 0 %d 0 %s Z" fill="%s"%s/>' % (
        pts((cx - dx, cut)), f(rx), f(ry), large, pts((cx + dx, cut)), fill, extra)


