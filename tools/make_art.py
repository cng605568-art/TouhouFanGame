def f(v):
    """Compact number formatting for path data."""
    s = ("%.2f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pts(*coords):
    return " ".join("%s %s" % (f(x), f(y)) for x, y in coords)


def svg(w, h, body, comment):
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- Fumo Court: %s. Generated by tools/make_art.py -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">\n'
        "%s\n</svg>\n" % (comment, w, h, w, h, body.strip("\n"))
    )


def gc(v, units):
    """
    Gradient coordinate. NanoSVG reads unitless bounding-box coordinates as
    pixels, so bounding-box gradients must be written as percentages.
    """
    return f(v) if units else f(v * 100) + "%"


def lin(id_, stops, x1=0, y1=0, x2=0, y2=1, units=None):
    u = ' gradientUnits="userSpaceOnUse"' if units else ""
    s = "".join(
        '<stop offset="%s" stop-color="%s"%s/>' % (
            f(o), c, (' stop-opacity="%s"' % f(a)) if a is not None else "")
        for o, c, a in [(st + (None,))[:3] for st in stops]
    )
    return '<linearGradient id="%s" x1="%s" y1="%s" x2="%s" y2="%s"%s>%s</linearGradient>' % (
        id_, gc(x1, units), gc(y1, units), gc(x2, units), gc(y2, units), u, s)


def rad(id_, stops, cx=0.5, cy=0.5, r=0.5, units=None, fx=None, fy=None):
    u = ' gradientUnits="userSpaceOnUse"' if units else ""
    fxy = ""
    if fx is not None:
        fxy = ' fx="%s" fy="%s"' % (gc(fx, units), gc(fy, units))
    s = "".join(
        '<stop offset="%s" stop-color="%s"%s/>' % (
            f(o), c, (' stop-opacity="%s"' % f(a)) if a is not None else "")
        for o, c, a in [(st + (None,))[:3] for st in stops]
    )
    return '<radialGradient id="%s" cx="%s" cy="%s" r="%s"%s%s>%s</radialGradient>' % (
        id_, gc(cx, units), gc(cy, units), gc(r, units), fxy, u, s)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def chamfer(x, y, w, h, c):
    """Rectangle with 45-degree cut corners (a signboard silhouette)."""
    return "M%s Z" % " L".join([
        pts((x + c, y)), pts((x + w - c, y)), pts((x + w, y + c)),
        pts((x + w, y + h - c)), pts((x + w - c, y + h)), pts((x + c, y + h)),
        pts((x, y + h - c)), pts((x, y + c)),
    ])


