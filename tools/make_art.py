def tomoe_mon(cx, cy, r, color):
    """Mitsudomoe: three comma shapes in a ring."""
    out = ['<circle cx="%s" cy="%s" r="%s" fill="none" stroke="%s" stroke-width="5"/>' % (f(cx), f(cy), f(r), color)]
    for k in range(3):
        a = math.radians(120 * k - 90)
        out.append('<g transform="translate(%s %s) rotate(%s) translate(0 %s)">%s</g>' % (
            f(cx), f(cy), f(120 * k), f(-r * 0.36), magatama_path(0, 0, r * 0.62, color, hole=None)))
    return "\n".join(out)


def asanoha_star(cx, cy, r, color):
    """Six hemp-leaf kites around a point, inside a ring."""
    out = ['<circle cx="%s" cy="%s" r="%s" fill="none" stroke="%s" stroke-width="5"/>' % (f(cx), f(cy), f(r), color)]
    for k in range(6):
        a = math.radians(60 * k - 90)
        ca, sa = math.cos(a), math.sin(a)
        tip = (cx + ca * r * 0.82, cy + sa * r * 0.82)
        mid = r * 0.34
        side = r * 0.17
        l = (cx + ca * mid - sa * side, cy + sa * mid + ca * side)
        rr = (cx + ca * mid + sa * side, cy + sa * mid - ca * side)
        out.append('<path d="M%s L%s L%s L%s Z" fill="%s"/>' % (pts((cx, cy)), pts(l), pts(tip), pts(rr), color))
    return "\n".join(out)


def magatama_path(cx, cy, s, fill, hole=CRIMSON, stroke=None, sw=0):
    """
    A magatama (comma bead) centred near (cx, cy), size s (head radius ~ s*0.5),
    head toward -y, tail sweeping clockwise.
    """
    r = s * 0.5
    hx, hy = cx, cy - s * 0.18
    d = "M%s C%s %s %s C%s %s %s A%s %s 0 1 1 %s Z" % (
        pts((hx + r, hy)),
        pts((hx + r, hy + r * 1.35)), pts((hx + r * 0.25, hy + r * 2.05)), pts((hx - r * 0.95, hy + r * 2.2)),
        pts((hx - r * 0.35, hy + r * 1.7)), pts((hx - r * 0.05, hy + r * 1.35)), pts((hx - r * 0.55, hy + r * 0.84)),
        f(r), f(r), pts((hx + r, hy)),
    )
    st = ""
    if stroke:
        st = ' stroke="%s" stroke-width="%s" stroke-linejoin="round"' % (stroke, f(sw))
    out = '<path d="%s" fill="%s"%s/>' % (d, fill, st)
    if hole:
        out += '<circle cx="%s" cy="%s" r="%s" fill="%s"/>' % (f(hx + r * 0.05), f(hy - r * 0.05), f(r * 0.28), hole)
    return out


def scales_shape(cx, top, size, color, pan_fill=None, sw=None):
    """Scales of justice as strokes + filled pans. size = overall height."""
    k = size / 300.0
    sw = sw or 9 * k
    pan_fill = pan_fill or color
    x = lambda v: cx + v * k
    y = lambda v: top + v * k
    out = []
    # Pillar and base
    out.append('<path d="M%s L%s" stroke="%s" stroke-width="%s" stroke-linecap="round"/>' % (pts((x(0), y(34))), pts((x(0), y(262))), color, f(sw * 1.15)))
    out.append('<path d="M%s L%s L%s L%s Z" fill="%s"/>' % (pts((x(-62), y(296))), pts((x(62), y(296))), pts((x(34), y(262))), pts((x(-34), y(262))), color))
    out.append('<rect x="%s" y="%s" width="%s" height="%s" fill="%s"/>' % (f(x(-74)), f(y(292)), f(148 * k), f(10 * k), color))
    # Finial
    out.append('<circle cx="%s" cy="%s" r="%s" fill="%s"/>' % (f(x(0)), f(y(22)), f(15 * k), color))
    # Beam
    out.append('<path d="M%s Q%s %s" fill="none" stroke="%s" stroke-width="%s" stroke-linecap="round"/>' % (
        pts((x(-118), y(70))), pts((x(0), y(48))), pts((x(118), y(70))), color, f(sw)))
    # Chains + pans
    for side in (-1, 1):
        px = x(118 * side)
        out.append('<path d="M%s L%s M%s L%s" fill="none" stroke="%s" stroke-width="%s" stroke-linecap="round"/>' % (
            pts((px, y(70))), pts((px - 46 * k, y(176))), pts((px, y(70))), pts((px + 46 * k, y(176))), color, f(sw * 0.45)))
        out.append('<path d="M%s Q%s %s Z" fill="%s" stroke="%s" stroke-width="%s" stroke-linejoin="round"/>' % (
            pts((px - 62 * k, y(176))), pts((px, y(236))), pts((px + 62 * k, y(176))), pan_fill, color, f(sw * 0.5)))
        out.append('<circle cx="%s" cy="%s" r="%s" fill="%s"/>' % (f(px), f(y(70)), f(8 * k), color))
    return "\n".join(out)


