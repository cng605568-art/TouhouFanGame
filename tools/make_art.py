def make_presplash():
    """Loading image for the desktop (game/presplash.png) and web builds."""
    exe = shutil.which("rsvg-convert")
    if not exe:
        print("rsvg-convert not found; skipping presplash")
        return
    from PIL import Image, ImageDraw, ImageFont
    tmp_bg = os.path.join(ROOT, "tools", "_bg.png")
    tmp_sc = os.path.join(ROOT, "tools", "_scales.png")
    subprocess.check_call([exe, "-w", "960", "-h", "540", "-o", tmp_bg, os.path.join(IMAGES, "bg_courtroom.svg")])
    subprocess.check_call([exe, "-w", "150", "-h", "150", "-o", tmp_sc, os.path.join(IMAGES, "scales.svg")])
    im = Image.open(tmp_bg).convert("RGBA")
    im.alpha_composite(Image.new("RGBA", im.size, (13, 2, 6, 150)))
    sc = Image.open(tmp_sc).convert("RGBA")
    im.alpha_composite(sc, ((960 - 150) // 2, 120))
    font = ImageFont.truetype(os.path.join(ROOT, "game", "fonts", "ShipporiMinchoB1-ExtraBold-sub.ttf"), 76)
    small = ImageFont.truetype(os.path.join(ROOT, "game", "fonts", "ShipporiMinchoB1-ExtraBold-sub.ttf"), 26)
    d = ImageDraw.Draw(im)
    for text, fnt, y, fill in (("FUMO COURT", font, 300, GOLD_HI), ("Shiki Eiki's Logic Trials", small, 398, PARCHMENT)):
        w = d.textlength(text, font=fnt)
        x = (960 - w) / 2
        d.text((x, y + 4), text, font=fnt, fill=(0, 0, 0, 150))
        d.text((x, y), text, font=fnt, fill=fill, stroke_width=3 if fnt is font else 2, stroke_fill=CRIMSON_DEEP)
    im = im.convert("RGB")
    im.save(os.path.join(ROOT, "web-presplash.png"), optimize=True)
    im.save(os.path.join(ROOT, "game", "presplash.png"), optimize=True)
    os.remove(tmp_bg)
    os.remove(tmp_sc)


