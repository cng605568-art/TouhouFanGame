def mirror(path_pts, cx=240):
    return [(2 * cx - x, y) for x, y in path_pts]


def bangs_path(edge, top=64, side_bottom=330, outer=74):
    """
    Front hair: outer helmet edge plus a scalloped fringe.
    `edge` lists fringe points right-to-left, alternating notch/tip.
    """
    d = ["M%s" % pts((outer + 22, side_bottom))]
    d.append("C%s %s %s" % (pts((outer - 8, 236)), pts((outer + 18, 118)), pts((176, 84))))
    d.append("C%s %s %s" % (pts((214, top + 4)), pts((266, top + 4)), pts((304, 84))))
    d.append("C%s %s %s" % (pts((480 - outer - 18, 118)), pts((480 - outer + 8, 236)), pts((480 - outer - 22, side_bottom))))
